function smallTalk(t, first) {
  const tt = t.trim().replace(/[!?.,🙂😊]+/g, ' ').replace(/\s+/g, ' ').trim();
  const howru = /מה נשמע|מה שלומך|מה קורה|מה המצב|מה העניינים|מה איתך|איך את|מה הולך|מה חדש/.test(tt);
  const hello = /^(היי|הי|שלום|ערב טוב|בוקר טוב|צהריים טובים|לילה טוב|אהלן|הלו|הייי+)( (לך|לכם))?( (מה נשמע|מה שלומך|מה קורה|מה המצב|מה העניינים|מה איתך|מה הולך|מה חדש))?$/.test(tt) || (howru && tt.split(' ').length <= 4);
  if (!hello) return null;
  const open = /בוקר טוב/.test(tt) ? 'בוקר אור! ☀️' : /ערב טוב/.test(tt) ? 'ערב טוב! 🌙' : pick(['שלום! 😊', 'היי! 😊', 'אהלן! 😊']);
  const how = howru ? pick([' הכל מעולה, תודה ששאלת! ואצלך?', ' הכל מצוין, ברוך השם, תודה!']) : '';
  return first ? open + how + ' ' + pick(['איך אוכל לעזור?', 'במה אפשר לעזור?']) : pick(['כן? אני כאן 😊', 'היי 😊 במה אפשר לעזור?']);
}
function grabName(t, asked) {
  let m;
  if ((m = t.match(/(קוראים לי|שמי|השם שלי|מדבר|מדברת)\s+([א-ת]{2,12})/)) && !NOT_NAMES.has(m[2])) return m[2];
  if (asked && !/\?/.test(t)) { const w = t.trim().replace(/[.,!]/g, '').replace(/^(אני|זה)\s+/, '').split(/\s+/).filter((x) => /^[א-ת]{2,12}$/.test(x) && !NOT_NAMES.has(x)); if (w.length && w.length <= 3) return w[0]; }
  return '';
}
