const LEAD_KEYS = {
  david: ['name', 'dates', 'nights', 'guests', 'apartment', 'occasion', 'extras', 'price', 'discount', 'arrival', 'budget', 'needs', 'questions'],
  lock: ['name', 'problem', 'urgent', 'city', 'when', 'details', 'questions'],
  clinic: ['name', 'treatment', 'area', 'firstTime', 'slot', 'offer', 'questions'],
};
LEAD_KEYS.dirot = LEAD_KEYS.david;
export function schemaFor(bot) {
  const keys = LEAD_KEYS[bot];
  return {
    type: 'object', additionalProperties: false,
    properties: {
      reply: { type: 'string', description: 'ההודעה ללקוח. עד 2 הודעות קצרות, מופרדות בשורה ריקה' },
      photos: { type: 'string', enum: ['', '1', '2', '3'], description: 'מספר הדירה שהתמונות שלה נשלחות עכשיו, או ריק' },
      route: { type: 'string', enum: ['', 'david', 'friends'] },
      lead: { type: 'object', additionalProperties: false, properties: Object.fromEntries(keys.map((k) => [k, { type: 'string' }])), required: keys },
      ready: { type: 'boolean' },
    },
    required: ['reply', 'photos', 'route', 'lead', 'ready'],
  };
}
export const BOTS = ['david', 'dirot', 'lock', 'clinic'];
export const isVacation = (bot) => bot === 'david' || bot === 'dirot';
export function promptFor(bot, today, opts = {}) {
  if (isVacation(bot)) return vacationPrompt(bot, today, opts);
  if (bot === 'lock') return lockPrompt(today);
  return clinicPrompt(today);
}
